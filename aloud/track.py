"""The description track, and the one rule it must never break.

The output of this pipeline is a timed track, the same artefact professional
audio description ships as. That is deliberate: it means the result is a
standard thing a player can consume, cacheable, inspectable, and reviewable by a
human describer before it goes out, rather than a bespoke stream only this app
understands.

The rule that matters: no cue may overlap dialogue. Everything else here is
formatting. A cue that lands on a line of dialogue does not merely fail to help,
it removes information the listener already had, which is worse than doing
nothing at all. So `validate` runs on every track before it is written and the
emitter refuses rather than warns.
"""
import json
from dataclasses import dataclass, field


@dataclass
class Cue:
    start: float
    end: float
    text: str
    audio: str | None = None
    gap: tuple[float, float] | None = None

    @property
    def duration(self) -> float:
        return self.end - self.start


@dataclass
class Track:
    cues: list = field(default_factory=list)
    source: str = ""
    # Provenance. A description track is reviewed by a person before it ships,
    # and the first question a reviewer asks is what wrote it.
    describer: str = ""
    voice: str = ""

    def validate(self, gaps, tolerance: float = 0.01) -> list[str]:
        """Every problem with this track, as plain sentences. Empty means good."""
        problems = []
        windows = [(g.start, g.end) for g in gaps]

        for i, c in enumerate(self.cues):
            if c.end <= c.start:
                problems.append(f"cue {i} ends before it starts")
                continue
            if not c.text.strip():
                problems.append(f"cue {i} has no text")
            inside = any(s - tolerance <= c.start and c.end <= e + tolerance
                         for s, e in windows)
            if not inside:
                problems.append(
                    f"cue {i} at {c.start:.2f}-{c.end:.2f}s is not inside any gap, "
                    "so it would play over dialogue")

        for a, b in zip(self.cues, self.cues[1:]):
            if b.start < a.end - tolerance:
                problems.append(
                    f"cues overlap each other at {b.start:.2f}s")
        return problems

    def to_vtt(self) -> str:
        def stamp(t):
            h, rem = divmod(max(0.0, t), 3600)
            m, s = divmod(rem, 60)
            return f"{int(h):02d}:{int(m):02d}:{s:06.3f}"

        out = ["WEBVTT", "", "NOTE Audio description generated by Aloud.",
               "NOTE Every cue sits inside a verified gap in the dialogue.", ""]
        for i, c in enumerate(self.cues, 1):
            out += [str(i), f"{stamp(c.start)} --> {stamp(c.end)}", c.text, ""]
        return "\n".join(out)

    def to_dict(self) -> dict:
        out = {"source": self.source}
        if self.describer:
            out["describer"] = self.describer
        if self.voice:
            out["voice"] = self.voice
        return {
            **out,
            "cues": [{"start": round(c.start, 3), "end": round(c.end, 3),
                      "text": c.text, "audio": c.audio,
                      "gap": list(c.gap) if c.gap else None} for c in self.cues],
        }

    def write(self, vtt_path: str | None = None, json_path: str | None = None,
              gaps=None) -> None:
        """Write the track, or refuse. Never write a track that would talk over
        dialogue: a file on disk gets shipped, and a warning gets ignored."""
        if gaps is not None:
            problems = self.validate(gaps)
            if problems:
                raise ValueError("refusing to write an unsafe track:\n  "
                                 + "\n  ".join(problems))
        if vtt_path:
            with open(vtt_path, "w") as f:
                f.write(self.to_vtt())
        if json_path:
            with open(json_path, "w") as f:
                json.dump(self.to_dict(), f, indent=2)


def schedule(gap, spoken_seconds: float, align: str = "start",
             lead_in: float = 0.0) -> tuple[float, float]:
    """Place a cue of known length inside a gap, and never outside it.

    Aligned to the start by default. A description is usually about what has
    just appeared, so saying it early gives the listener the context while the
    image is still on screen, rather than confirming afterwards what they have
    already stopped wondering about.

    Every branch clamps to the gap. `centre` did not, and returned an end three
    seconds past a two second gap when handed a cue too long to fit: the exact
    overrun this whole system exists to prevent. It was unreachable in practice
    because the pipeline only asks for cues that already fit, which is precisely
    why nothing caught it. `align` is a public argument, and a safety property
    that holds only because of how one caller happens to behave is not a safety
    property.
    """
    if align == "end":
        end = gap.end
        return max(gap.start, end - spoken_seconds), end
    if align == "centre":
        slack = max(0.0, gap.duration - spoken_seconds)
        start = gap.start + slack / 2
        return start, min(gap.end, start + spoken_seconds)
    start = gap.start + lead_in
    return start, min(gap.end, start + spoken_seconds)
